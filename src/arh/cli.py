"""Command line entry point: ``arh run`` (or ``python -m arh``)."""

from __future__ import annotations

import argparse
import re
from pathlib import Path

from .defenses.config import PRESETS
from .defenses.policy import get_engine
from .models.base import get_model
from .report import category_table, results_table, write_reports
from .runner import run_suite

README_START, README_END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="arh", description="Red-team evaluation harness for tool-using LLM agents.")
    sub = p.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("run", help="run the suite and write reports")
    r.add_argument("--model", default="mock", help="mock | bedrock:<model-id> | anthropic:<model> | openai:<model>")
    r.add_argument("--configs", default=",".join(PRESETS), help="comma-separated defense presets")
    r.add_argument("--policy-engine", default="python", choices=["python", "opa"])
    r.add_argument("--out", default="reports")
    r.add_argument("--update-readme", action="store_true", help="refresh the results block in README.md")
    sub.add_parser("list", help="list cases and defense presets")
    a = p.parse_args(argv)

    if a.cmd == "list":
        from .suite import CASES
        for c in CASES:
            print(f"{c.id:7} {c.kind:6} {c.category:20} {c.title}")
        print("\nPresets:", ", ".join(PRESETS))
        return 0

    run = run_suite(get_model(a.model), a.configs.split(","), get_engine(a.policy_engine))
    jp, mp = write_reports(run, Path(a.out))
    print(results_table(run))
    print()
    print(category_table(run))
    print(f"\nWrote {jp} and {mp}")
    if a.update_readme:
        readme = Path("README.md")
        block = (f"{README_START}\n_Generated by `arh run --update-readme` with model `{run['model']}`._\n\n"
                 + results_table(run) + "\n\nAttack success by category (succeeded/total):\n\n"
                 + category_table(run) + f"\n{README_END}")
        text = readme.read_text()
        readme.write_text(re.sub(re.escape(README_START) + r".*?" + re.escape(README_END), lambda _: block, text, flags=re.S))
        print("Updated README.md results block")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
